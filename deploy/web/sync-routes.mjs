#!/usr/bin/env node
// Regenerate deploy/web/spa-routes.txt (the nginx input of gen-routes.sh) from src/spa/routes.config.ts, the ONE
// source of which routes the SPA serves. Every route is an EXACT line ("=/path"); a dynamic segment carries "!name"
// tokens for the static sibling pages it must not swallow (computed from src/app/(app), same function the SPA uses).
//   node deploy/web/sync-routes.mjs           write spa-routes.txt
//   node deploy/web/sync-routes.mjs --check   exit 1 (and print the diff) when the committed file is stale
// Needs Node >= 22.18 (runs the .ts sources directly); nothing here is needed on the droplet, which only reads the txt.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "../../src");
const load = (rel) => import(pathToFileURL(path.join(src, rel)).href);
const { SPA_ROUTES } = await load("spa/routes.config.ts");
const { exclusionsFor } = await load("spa/route-table.ts");
const { allAppPageRoutes } = await load("spa/app-pages.node.ts");

export function render() {
  const pages = allAppPageRoutes(src);
  const missing = SPA_ROUTES.filter((r) => !pages.includes(r) && !pages.includes(r.replace(/\/$/, "")));
  const lines = [
    "# GENERATED by deploy/web/sync-routes.mjs from src/spa/routes.config.ts - do not edit by hand.",
    "# Add or remove a route in routes.config.ts, run `node deploy/web/sync-routes.mjs`, then gen-routes.sh --apply.",
    "# Every line is EXACT (=/path, optional trailing slash, sub-paths stay on Next). [param] = one path segment; the",
    "# !name tokens are static sibling pages the [param] segment must not match (they are separate Next pages).",
    "# Denied (gen-routes.sh refuses): /api /.well-known /oauth /web /sw.js /try-demo and /",
    "",
  ];
  for (const r of SPA_ROUTES) {
    const ex = exclusionsFor(r, pages);
    lines.push(`=${r}${ex.map((e) => ` !${e}`).join("")}`);
  }
  if (missing.length) throw new Error(`routes.config.ts lists routes without a page.tsx under src/app/(app): ${missing.join(", ")}`);
  return lines.join("\n") + "\n";
}

const out = path.join(here, "spa-routes.txt");
const next = render();
if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(out, "utf8"); } catch {}
  if (cur !== next) {
    console.error("deploy/web/spa-routes.txt is stale vs src/spa/routes.config.ts; run: node deploy/web/sync-routes.mjs");
    process.exit(1);
  }
  console.log("spa-routes.txt in sync");
} else {
  writeFileSync(out, next);
  console.log(`wrote ${out} (${next.trim().split("\n").filter((l) => l.startsWith("=")).length} routes)`);
}
