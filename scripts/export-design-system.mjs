// ── CLI ───────────────────────────────────────────────────────────────────────────────────────────────────────
const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = process.argv.slice(2);
  const arg = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const manifestPath = path.resolve(root, arg("--manifest") ?? "design-system/export.manifest.json");
  try {
    const checkDir = arg("--check-lock");
    if (checkDir) {
      const lock = JSON.parse(fs.readFileSync(path.join(checkDir, "MANIFEST.lock"), "utf8"));
      const fresh = runExport({ root, manifestPath, outDir: null }).lock;
      const drift = [];
      for (const [p, f] of Object.entries(fresh.files)) {
        const old = lock.files[p];
        if (!old) drift.push(`new file not in lock: ${p}`);
        else if (old.srcSha256 !== f.srcSha256 || old.sha256 !== f.sha256) drift.push(`changed: ${p} (${f.src})`);
      }
      for (const p of Object.keys(lock.files)) if (!fresh.files[p]) drift.push(`removed from source: ${p}`);
      for (const [p, f] of Object.entries(lock.files)) {
        const fp = path.join(checkDir, p);
        if (!fs.existsSync(fp)) drift.push(`missing on disk: ${p}`);
        else if (sha256(fs.readFileSync(fp)) !== f.sha256) drift.push(`edited by hand: ${p}`);
      }
      if (drift.length) { console.error(`DRIFT (${drift.length}); re-run: npm run ds:export -- --out ${checkDir}\n  - ${drift.join("\n  - ")}`); process.exit(1); }
      console.log(`no drift (${Object.keys(fresh.files).length} files, source ${fresh.sourceSha})`);
    } else {
      const outDir = arg("--out");
      if (!outDir) { console.error("usage: export-design-system.mjs --out <ds dir> | --check-lock <ds dir>"); process.exit(2); }
      const r = runExport({ root, manifestPath, outDir: path.resolve(outDir), log: (m) => console.log(m) });
      console.log(`exported ${Object.keys(r.lock.files).length} files -> ${outDir} (${r.lock.package}); entries: ${r.activeEntries.join(", ")}`);
      console.log(`peerDependencies: ${Object.entries(r.peers).map(([k, v]) => `${k}@${v}`).join(" ")}`);
    }
  } catch (e) {
    console.error(e instanceof ExportError ? `EXPORT FAILED: ${e.message}` : e);
    process.exit(1);
  }
}
