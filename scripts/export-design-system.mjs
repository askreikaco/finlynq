#!/usr/bin/env node
/**
 * Export the REIKA design system (@reika/ui) from the Finlynq source.
 *
 *   node scripts/export-design-system.mjs --out ../reika-ai/ds
 *   node scripts/export-design-system.mjs --check-lock ../reika-ai/ds     (drift check, writes nothing)
 *
 * Reads design-system/export.manifest.json, copies the listed source files, rewrites imports (alias -> relative,
 * app-coupled -> adapters via manifest rules), and generates: ui/ (the package), tokens/, css/reika.css,
 * MANIFEST.lock, export.manifest.json. Node built-ins only. Fails loudly (all problems listed) on a missing file,
 * an unmapped import, a duplicate export name or an unknown adapter name.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const sha256 = (buf) => crypto.createHash("sha256").update(buf).digest("hex");
const posix = (p) => p.split(path.sep).join("/");
const EXT = [".ts", ".tsx"];
const BANNER = (src) => `// GENERATED by finlynq scripts/export-design-system.mjs from ${src}. Do not edit; change the source and re-export.\n`;

class ExportError extends Error {
  constructor(title, lines) {
    super(`${title}\n${lines.map((l) => `  - ${l}`).join("\n")}`);
    this.name = "ExportError";
  }
}

/** Blank out comments (same length, newlines kept) so import scanning ignores prose like: from "x". */
function maskComments(text) {
  let out = "";
  let i = 0;
  let quote = null;
  while (i < text.length) {
    const c = text[i];
    const n = text[i + 1];
    if (quote) {
      out += c;
      if (c === "\\") { out += n ?? ""; i += 2; continue; }
      if (c === quote) quote = null;
      i++;
      continue;
    }
    if (c === "'" || c === '"' || c === "`") { quote = c; out += c; i++; continue; }
    if (c === "/" && n === "/") {
      while (i < text.length && text[i] !== "\n") { out += " "; i++; }
      continue;
    }
    if (c === "/" && n === "*") {
      while (i < text.length && !(text[i] === "*" && text[i + 1] === "/")) { out += text[i] === "\n" ? "\n" : " "; i++; }
      out += "  "; i += 2;
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

function walkDir(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walkDir(p, out);
    else if (EXT.includes(path.extname(e.name))) out.push(p);
  }
  return out;
}

function gitShortSha(root) {
  try {
    return execFileSync("git", ["rev-parse", "--short=8", "HEAD"], { cwd: root, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    return "nogit";
  }
}

/** Extract text between markers. `to` null = end of file. A marker inside a comment cuts back to that comment's start. */
function region(css, r, label) {
  const a = css.indexOf(r.from);
  if (a < 0) throw new ExportError("tokens: start marker not found", [`${label}/${r.id}: ${JSON.stringify(r.from)}`]);
  let b = css.length;
  if (r.to != null) {
    b = css.indexOf(r.to, a + r.from.length);
    if (b < 0) throw new ExportError("tokens: end marker not found", [`${label}/${r.id}: ${JSON.stringify(r.to)}`]);
    const open = css.lastIndexOf("/*", b);
    if (open > a && !css.slice(open, b).includes("*/")) b = open;
  }
  return css.slice(a, b).trimEnd() + "\n";
}

export function runExport({ root, manifestPath, outDir, log = () => {} }) {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  const sha = gitShortSha(root);
  const abs = (p) => path.join(root, p);

  // ── 1. active entries, expand sources, fail loudly on missing ───────────────────────────────────────────────
  const missing = [];
  const files = new Map(); // src (posix, relative to root) -> { entryId }
  const active = [];
  for (const entry of manifest.entries) {
    const sentinel = (entry.retiredWhenPresent ?? []).find((s) => fs.existsSync(abs(s)));
    if (sentinel) { log(`skip entry "${entry.id}": retired (${sentinel} exists)`); continue; }
    active.push(entry);
    for (const s of entry.src) {
      const p = abs(s);
      if (!fs.existsSync(p)) { missing.push(`${entry.id}: ${s}`); continue; }
      if (fs.statSync(p).isDirectory()) {
        for (const f of walkDir(p)) files.set(posix(path.relative(root, f)), { entryId: entry.id });
      } else files.set(s, { entryId: entry.id });
    }
    for (const pub of entry.public ?? []) {
      const f = typeof pub === "string" ? pub : pub.file;
      if (!fs.existsSync(abs(f))) missing.push(`${entry.id} (public): ${f}`);
    }
  }
  for (const [label, p] of [["adapters template", manifest.adapters.template], ["tsconfig template", manifest.tsconfigTemplate], ["reika.css template", manifest.reikaCss], ["tokens css", manifest.tokens.css], ...manifest.tokens.vendorCss.map((v) => ["vendor css", v.path])]) {
    if (!fs.existsSync(abs(p))) missing.push(`${label}: ${p}`);
  }
  if (missing.length) throw new ExportError(`export.manifest.json lists ${missing.length} missing file(s) (rename, merge refactor or typo). Fix the manifest or restore the file`, missing);

  // ── 2. destinations ─────────────────────────────────────────────────────────────────────────────────────────
  const destOf = (src) => {
    for (const m of manifest.destMap) if (src.startsWith(m.from)) return m.to + src.slice(m.from.length);
    throw new ExportError("no destMap prefix for", [src]);
  };
  const srcToDest = new Map();
  const destToSrc = new Map();
  const problems = [];
  for (const src of files.keys()) {
    const d = destOf(src);
    if (destToSrc.has(d)) problems.push(`two sources map to ${d}: ${destToSrc.get(d)} and ${src}`);
    destToSrc.set(d, src);
    srcToDest.set(src, d);
  }
  const adaptersDest = manifest.adapters.dest;
  const adaptersBase = adaptersDest.replace(/\.(tsx?|ts)$/, "");
  if (destToSrc.has(adaptersDest)) problems.push(`adapters dest collides with ${destToSrc.get(adaptersDest)}`);
  if (problems.length) throw new ExportError("destination collisions", problems);

  const resolveSrc = (base) => {
    for (const e of ["", ...EXT]) if (files.has(base + e)) return base + e;
    for (const e of EXT) if (files.has(`${base}/index${e}`)) return `${base}/index${e}`;
    return null;
  };
  const relImport = (fromDest, toDest) => {
    let t = toDest.replace(/\.(tsx?|ts)$/, "");
    if (t.endsWith("/index")) t = t.slice(0, -6);
    let r = posix(path.relative(path.posix.dirname(fromDest) || ".", t)) || ".";
    if (!r.startsWith(".")) r = "./" + r;
    return r;
  };

  // adapters export names (for rewrite checks)
  const adaptersTpl = fs.readFileSync(abs(manifest.adapters.template), "utf8");
  const adapterNames = scanExports(adaptersTpl).all;

  // ── 3. rewrite + write into memory ──────────────────────────────────────────────────────────────────────────
  const out = new Map(); // path relative to <out>/ui  -> { content, src }
  const usedRules = new Set();
  const peers = new Set();
  const errors = [];
  const SPEC_RE = /(\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)(["'])([^"'\n]+)\2/g;

  for (const [src, dest] of srcToDest) {
    const text = fs.readFileSync(abs(src), "utf8");
    const masked = maskComments(text);
    let result = "";
    let last = 0;
    let m;
    SPEC_RE.lastIndex = 0;
    while ((m = SPEC_RE.exec(masked))) {
      const spec = m[3];
      const specStart = m.index + m[1].length + 1;
      const specEnd = specStart + spec.length;
      let newSpec = spec;
      let stmtPatch = null; // [start, end, replacement] for default-to-named
      const rule = manifest.rewrites.find((r) => r.match === spec && (!r.files || r.files.includes(src)));
      if (rule) {
        usedRules.add(rule.id);
        if (rule.kind === "module") newSpec = relImport(dest, adaptersDest);
        else if (rule.kind === "module-file") {
          const t = resolveSrc(rule.to.replace(/\.(tsx?)$/, "")) ?? (files.has(rule.to) ? rule.to : null);
          if (!t) errors.push(`${src}: rule ${rule.id} target ${rule.to} is not exported by any entry`);
          else newSpec = relImport(dest, srcToDest.get(t));
        } else if (rule.kind === "default-to-named") {
          const stmtStart = masked.lastIndexOf("import", m.index);
          const clause = masked.slice(stmtStart + 6, m.index).trim();
          const dm = /^(\w+)$/.exec(clause);
          if (!dm) errors.push(`${src}: rule ${rule.id} expects a plain default import, found "${clause}"`);
          else {
            const local = dm[1];
            stmtPatch = [stmtStart, specEnd + 1, `import { ${local === rule.name ? local : `${rule.name} as ${local}`} } from "${relImport(dest, adaptersDest)}"`];
          }
        }
      } else if (spec.startsWith("@/") || spec.startsWith(".")) {
        const base = spec.startsWith("@/") ? "src/" + spec.slice(2) : path.posix.normalize(path.posix.join(path.posix.dirname(src), spec));
        const t = resolveSrc(base);
        if (!t) errors.push(`${src}: import "${spec}" is not in the package (add it to an entry or write a rewrite rule)`);
        else newSpec = relImport(dest, srcToDest.get(t));
      } else if (spec.startsWith("next/") || spec.startsWith("@shared/") || spec === "next") {
        errors.push(`${src}: import "${spec}" has no rewrite rule`);
      } else if (!spec.startsWith("node:")) {
        const parts = spec.split("/");
        peers.add(spec.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0]);
      }
      if (stmtPatch) {
        result += text.slice(last, stmtPatch[0]) + stmtPatch[2];
        last = stmtPatch[1];
      } else if (newSpec !== spec) {
        result += text.slice(last, specStart) + newSpec;
        last = specEnd;
      }
    }
    result += text.slice(last);
    out.set(dest, { content: BANNER(src) + result, src, srcSha: sha256(fs.readFileSync(abs(src))) });
  }

  // adapters + tsconfig
  out.set(adaptersDest, { content: BANNER(manifest.adapters.template) + adaptersTpl, src: manifest.adapters.template, srcSha: sha256(adaptersTpl) });
  const tsconfigTpl = fs.readFileSync(abs(manifest.tsconfigTemplate), "utf8");
  out.set("tsconfig.json", { content: tsconfigTpl, src: manifest.tsconfigTemplate, srcSha: sha256(tsconfigTpl) });

  // adapters imports used by output must exist in adapters
  for (const [dest, f] of out) {
    if (dest === adaptersDest || !/\.tsx?$/.test(dest)) continue;
    const masked = maskComments(f.content);
    const re = /import\s+(?:type\s+)?\{([^}]*)\}\s*from\s*["']([^"']+)["']/g;
    let m;
    while ((m = re.exec(masked))) {
      const target = path.posix.normalize(path.posix.join(path.posix.dirname(dest), m[2]));
      if (target !== adaptersBase) continue;
      for (const part of m[1].split(",")) {
        const name = part.trim().replace(/^type\s+/, "").split(/\s+as\s+/)[0].trim();
        if (name && !adapterNames.has(name)) errors.push(`${dest}: imports "${name}" from adapters, but the adapters template does not export it`);
      }
    }
  }
  for (const r of manifest.rewrites) if (!usedRules.has(r.id)) log(`note: rewrite rule "${r.id}" matched nothing in this export`);
  if (errors.length) throw new ExportError(`${errors.length} import problem(s)`, errors);

  // ── 4. barrels ──────────────────────────────────────────────────────────────────────────────────────────────
  const entryBarrels = new Map(); // entry id -> content
  const seenNames = new Map();
  const dupes = [];
  const exportsOfDest = (dest, only, seen = new Set()) => {
    if (seen.has(dest)) return { values: new Set(), types: new Set() };
    seen.add(dest);
    const f = out.get(dest);
    if (!f) throw new ExportError("barrel", [`public module ${dest} not generated`]);
    const sc = scanExports(f.content);
    const values = new Set(sc.values);
    const types = new Set(sc.types);
    f.own = sc.own;
    for (const star of sc.stars) {
      const t = resolveOutRel(dest, star, out);
      if (t) { const sub = exportsOfDest(t, null, seen); sub.values.forEach((v) => values.add(v)); sub.types.forEach((v) => types.add(v)); }
    }
    if (only) { for (const v of [...values]) if (!only.includes(v)) values.delete(v); for (const v of [...types]) if (!only.includes(v)) types.delete(v); }
    return { values, types };
  };
  for (const entry of active) {
    const lines = [`// GENERATED barrel for entry "${entry.id}" (${entry.title}).`];
    for (const pub of entry.public ?? []) {
      const srcFile = typeof pub === "string" ? pub : pub.file;
      const dest = srcToDest.get(srcFile);
      const { values, types } = exportsOfDest(dest, typeof pub === "string" ? null : pub.only);
      const rel = relImport(`entries/${entry.id}.ts`, dest);
      for (const n of [...values, ...types]) {
        const prev = seenNames.get(n);
        if (prev && prev !== `${entry.id}:${dest}`) {
          // a later module that only RE-exports a name defined earlier is not a conflict: keep the first, drop the repeat
          if (!(out.get(dest).own?.has(n))) { values.delete(n); types.delete(n); continue; }
          dupes.push(`"${n}" exported by ${prev} and ${entry.id}:${dest}`);
        }
        seenNames.set(n, `${entry.id}:${dest}`);
      }
      const vs = [...values].filter((v) => !types.has(v)).sort();
      const ts = [...types].sort();
      if (vs.length) lines.push(`export { ${vs.join(", ")} } from "${rel}";`);
      if (ts.length) lines.push(`export type { ${ts.join(", ")} } from "${rel}";`);
    }
    entryBarrels.set(entry.id, lines.join("\n") + "\n");
  }
  if (dupes.length) throw new ExportError("duplicate export names across entries (use `only` in public to narrow)", dupes);
  for (const [id, content] of entryBarrels) out.set(`entries/${id}.ts`, { content, src: "(generated)", srcSha: "" });
  const indexLines = [
    "// GENERATED root barrel of @reika/ui.",
    `export { configureReikaUi, getReikaUiConfig } from "./${adaptersBase}";`,
    `export type { ReikaUiConfig, LinkProps } from "./${adaptersBase}";`,
    ...active.map((e) => `export * from "./entries/${e.id}";`),
  ];
  out.set("index.ts", { content: indexLines.join("\n") + "\n", src: "(generated)", srcSha: "" });

  // ── 5. package.json, README.usage.md ────────────────────────────────────────────────────────────────────────
  for (const p of manifest.tokens.peerImports ?? []) peers.add(p);
  for (const p of manifest.package.extraPeers ?? []) peers.add(p);
  const srcPkg = JSON.parse(fs.readFileSync(abs("package.json"), "utf8"));
  const range = (name) => {
    const r = manifest.package.peerRanges?.[name] ?? srcPkg.dependencies?.[name] ?? srcPkg.devDependencies?.[name];
    if (!r) errors.push(`no version range for peer "${name}" (add package.peerRanges.${name})`);
    return r;
  };
  const peerDependencies = {};
  for (const p of [...peers].sort()) peerDependencies[p] = range(p);
  if (errors.length) throw new ExportError("peer ranges", errors);
  const exportsMap = {
    ".": "./index.ts",
    "./adapters": `./${adaptersDest}`,
    "./tokens.css": "./tokens.css",
    "./package.json": "./package.json",
  };
  for (const e of active) exportsMap[`./${e.id}`] = `./entries/${e.id}.ts`;
  const pkg = {
    name: manifest.package.name,
    version: `${manifest.package.baseVersion}+${sha}`,
    description: manifest.package.description,
    type: "module",
    license: "UNLICENSED",
    main: "./index.ts",
    types: "./index.ts",
    sideEffects: ["./tokens.css"],
    exports: exportsMap,
    peerDependencies,
    peerDependenciesMeta: { tailwindcss: { optional: false } },
  };
  out.set("package.json", { content: JSON.stringify(pkg, null, 2) + "\n", src: "(generated)", srcSha: "" });

  const usage = [`# ${manifest.package.name} usage (generated)\n`,
    "```css\n/* app.css */\n@import \"tailwindcss\";\n@import \"./reika-ui/tokens.css\";\n@source \"./reika-ui\";\n```\n",
    "```tsx\n// entry file, once, only to override defaults\nimport { configureReikaUi } from \"@reika/ui\";\nconfigureReikaUi({ Link, useNavigate, formatMoney, formatDate, t, useSizeClass });\n```\n"];
  for (const e of active) usage.push(`## ${e.title}\n\n\`\`\`tsx\n${e.usage.join("\n")}\n\`\`\`\n`);
  out.set("README.usage.md", { content: usage.join("\n"), src: "(generated)", srcSha: "" });

  // usage snippets: every identifier in `import { ... } from '@reika/ui'` must be exported
  const rootNames = new Set(seenNames.keys());
  rootNames.add("configureReikaUi");
  const usageErr = [];
  for (const e of active) {
    for (const line of e.usage) {
      const m = /import\s*\{([^}]+)\}\s*from\s*['"]@reika\/ui(?:\/\w+)?['"]/.exec(line);
      if (m) for (const n of m[1].split(",").map((s) => s.trim())) if (n && !rootNames.has(n)) usageErr.push(`${e.id}: usage imports "${n}" which the barrel does not export`);
    }
  }
  if (usageErr.length) throw new ExportError("usage snippets reference unknown exports", usageErr);

  // ── 6. tokens ───────────────────────────────────────────────────────────────────────────────────────────────
  const css = fs.readFileSync(abs(manifest.tokens.css), "utf8");
  const tk = manifest.tokens;
  const gen = (what) => `/* GENERATED by finlynq scripts/export-design-system.mjs from ${tk.css}${what ? " (" + what + ")" : ""}. Do not edit. */\n`;
  const plain = tk.plain.map((r) => region(css, r, "plain")).join("\n");
  const tailwind = tk.tailwind.map((r) => region(css, r, "tailwind")).join("\n");
  const base = tk.base.map((r) => region(css, r, "base")).join("\n");
  const vendor = tk.vendorCss.map((v) => `/* vendored: ${v.label} */\n` + fs.readFileSync(abs(v.path), "utf8")).join("\n");
  const imports = (tk.peerImports ?? []).map((p) => `@import "${p}";`).join("\n");
  const tokensCss = `${gen("plain CSS custom properties: light + dark, framework-neutral")}\n${plain}`;
  const tailwindCss = `${gen("Tailwind v4 variants + @theme mapping")}/* Use after: @import "tailwindcss"; @import "./tokens.css"; */\n\n${tailwind}`;
  const uiTokens = `${imports}\n${gen("Tailwind entry for @reika/ui: tokens + theme + base layers")}/* Use after: @import "tailwindcss"; */\n/* Scan this package for utility classes: Tailwind skips gitignored dirs and node_modules unless told. */\n@source "./";\n\n${vendor}\n\n/* === tailwind theme === */\n${tailwind}\n/* === tokens === */\n${plain}\n/* === base / component layers === */\n${base}`;
  out.set("tokens.css", { content: uiTokens, src: tk.css, srcSha: sha256(css) });

  // ds-level extra outputs (paths relative to <out>/)
  const extra = new Map();
  extra.set("tokens/tokens.css", { content: tokensCss, src: tk.css, srcSha: sha256(css) });
  extra.set("tokens/tailwind-theme.css", { content: tailwindCss, src: tk.css, srcSha: sha256(css) });
  const vars = parseVars(tokensCss);
  extra.set("tokens/bricks-variables.json", { content: JSON.stringify(bricksVariables(vars), null, 2) + "\n", src: tk.css, srcSha: sha256(css) });
  extra.set("tokens/frappe-overrides.css", { content: frappeOverrides(gen), src: tk.css, srcSha: sha256(css) });
  const reika = fs.readFileSync(abs(manifest.reikaCss), "utf8");
  extra.set("css/reika.css", { content: reika, src: manifest.reikaCss, srcSha: sha256(reika) });
  for (const w of manifest.web ?? []) {
    if (!fs.existsSync(abs(w.template))) throw new ExportError("missing web template", [w.template]);
    const buf = fs.readFileSync(abs(w.template));
    extra.set(w.dest, { content: buf.toString("utf8"), src: w.template, srcSha: sha256(buf) });
  }
  extra.set("export.manifest.json", { content: fs.readFileSync(manifestPath, "utf8"), src: posix(path.relative(root, manifestPath)), srcSha: sha256(fs.readFileSync(manifestPath)) });

  // ── 7. lock + write ─────────────────────────────────────────────────────────────────────────────────────────
  const all = new Map();
  for (const [p, f] of out) all.set(`ui/${p}`, f);
  for (const [p, f] of extra) all.set(p, f);
  const lock = {
    generator: "finlynq scripts/export-design-system.mjs",
    sourceRepo: "askreikaco/finlynq",
    sourceSha: sha,
    package: `${manifest.package.name}@${pkg.version}`,
    files: Object.fromEntries([...all].sort(([a], [b]) => a.localeCompare(b)).map(([p, f]) => [p, { src: f.src, srcSha256: f.srcSha, sha256: sha256(f.content) }])),
  };
  const lockText = JSON.stringify(lock, null, 2) + "\n";

  if (outDir) {
    const prevLockPath = path.join(outDir, "MANIFEST.lock");
    if (fs.existsSync(prevLockPath)) {
      try {
        for (const old of Object.keys(JSON.parse(fs.readFileSync(prevLockPath, "utf8")).files)) {
          if (!all.has(old)) fs.rmSync(path.join(outDir, old), { force: true });
        }
      } catch { /* unreadable previous lock: leave files alone */ }
    }
    for (const [p, f] of all) {
      const target = path.join(outDir, p);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, f.content);
    }
    fs.writeFileSync(path.join(outDir, "MANIFEST.lock"), lockText);
  }
  return { lock, files: all, peers: peerDependencies, adapterNames, pkg, activeEntries: active.map((e) => e.id) };
}

// ── helpers ───────────────────────────────────────────────────────────────────────────────────────────────────

function resolveOutRel(fromDest, rel, out) {
  const base = path.posix.normalize(path.posix.join(path.posix.dirname(fromDest), rel));
  for (const e of ["", ".ts", ".tsx", "/index.ts", "/index.tsx"]) if (out.has(base + e)) return base + e;
  return null;
}

/** Named exports of a module's text: values, types, `export *` targets. Default exports are ignored. */
export function scanExports(text) {
  const t = maskComments(text);
  const values = new Set();
  const types = new Set();
  const stars = [];
  let m;
  const own = new Set();
  const rv = /\bexport\s+(?:async\s+)?(?:function\*?|const|let|var|class|enum)\s+(\w+)/g;
  while ((m = rv.exec(t))) { values.add(m[1]); own.add(m[1]); }
  const rt = /\bexport\s+(?:type|interface)\s+(\w+)/g;
  while ((m = rt.exec(t))) { types.add(m[1]); own.add(m[1]); }
  const rl = /\bexport\s+(type\s+)?\{([^}]*)\}/g;
  while ((m = rl.exec(t))) {
    for (const part of m[2].split(",")) {
      const p = part.trim().replace(/^type\s+/, "");
      if (!p) continue;
      const name = p.split(/\s+as\s+/).pop().trim();
      if (name === "default") continue;
      (m[1] || /^\s*type\s/.test(part) ? types : values).add(name);
    }
  }
  const rs = /\bexport\s+\*\s+from\s*["']([^"']+)["']/g;
  while ((m = rs.exec(t))) stars.push(m[1]);
  return { values, types, stars, own, all: new Set([...values, ...types]) };
}

function parseVars(css) {
  const light = {};
  const dark = {};
  const blockRe = /(^|\n)(:root|\.dark)\s*\{([\s\S]*?)\n\}/g;
  let m;
  while ((m = blockRe.exec(css))) {
    const target = m[2] === ":root" ? light : dark;
    const body = m[3].replace(/\/\*[\s\S]*?\*\//g, "");
    for (const d of body.split(/;\s*(?:\n|$)/)) {
      const dm = /^\s*(--[\w-]+)\s*:\s*([\s\S]+?)\s*$/.exec(d);
      if (dm) target[dm[1]] = dm[2].replace(/\s+/g, " ");
    }
  }
  return { light, dark };
}

function bricksVariables({ light, dark }) {
  const keep = (k) => !/^--(glass|tab|bar|hit|press|phone|mobile|form|sa[tbrl]|blur|header|sidebar)/.test(k);
  const mk = (rec, suffix) => Object.entries(rec).filter(([k]) => keep(k)).map(([k, v]) => ({ id: `reika-${k.slice(2)}${suffix}`, name: k.slice(2) + suffix, value: v }));
  return {
    $comment: "Best-effort Bricks global-variable set (id/name/value). Light values = :root, dark values = .dark. Not verified by import into a live Bricks install.",
    category: { id: "reika-ds", name: "REIKA Design System" },
    variables: mk(light, ""),
    darkVariables: mk(dark, "-dark"),
  };
}

