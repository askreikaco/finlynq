/**
 * One source of truth: src/spa/routes.config.ts -> (route-table.ts matchers in the browser/SW) and
 * (deploy/web/spa-routes.txt -> gen-routes.sh -> nginx regexes). These tests prove the two agree and that the
 * committed spa-routes.txt is not stale.
 */
import { describe, expect, it } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { SPA_ROUTES } from "@/spa/routes.config";
import { exclusionsFor, makeIsSpaPath, routeSource } from "@/spa/route-table";
import { allAppPageRoutes } from "@/spa/app-pages.node";

const root = path.resolve(__dirname, "../..");
const pages = allAppPageRoutes(path.join(root, "src"));
const isSpa = makeIsSpaPath(SPA_ROUTES, pages);

describe("SPA route table", () => {
  it("every enabled route has a page.tsx under (app)", () => {
    for (const r of SPA_ROUTES) expect(pages, r).toContain(r);
  });

  it("no duplicates, no reserved prefixes", () => {
    expect(new Set(SPA_ROUTES).size).toBe(SPA_ROUTES.length);
    for (const r of SPA_ROUTES) expect(r).not.toMatch(/^\/(api|\.well-known|oauth|web|sw\.js|try-demo)(\/|$)/);
  });

  it("matches exactly the listed paths (optional trailing slash and query)", () => {
    for (const p of ["/dashboard", "/dashboard/", "/dashboard?range=this_year", "/transactions", "/transactions?sel=12", "/transactions/new", "/transactions/search?q=a",
      "/transactions/9/edit", "/accounts", "/accounts/new", "/accounts/12", "/categories?sel=new", "/filter/accounts?returnTo=/accounts", "/more", "/settings", "/settings/about"]) {
      expect(isSpa(p), p).toBe(true);
    }
    for (const p of ["/", "/dashboardx", "/dashboard/x", "/more/x", "/settings/general", "/transactions/9", "/transactions/9/split", "/transactions/9/edit/x",
      "/accounts/12/edit", "/accounts/12/x", "/categories/5", "/filter", "/filter/a/b", "/api/accounts", "/budgets", "/portfolio/new/buy"]) {
      expect(isSpa(p), p).toBe(false);
    }
  });

  it("a dynamic segment never swallows a static sibling page (they are separate Next pages)", () => {
    expect(isSpa("/accounts/groups")).toBe(false);
    expect(isSpa("/accounts/groups/")).toBe(false);
    expect(isSpa("/transactions/audit/edit")).toBe(false);
    expect(isSpa("/transactions/transfer/5/edit")).toBe(false);
    expect(isSpa("/accounts/grouped")).toBe(true);
    expect(exclusionsFor("/accounts/[id]", pages)).toEqual(expect.arrayContaining(["groups", "new"]));
    expect(exclusionsFor("/dashboard", pages)).toEqual([]);
  });

  it("routeSource is anchored and escapes literals", () => {
    expect(routeSource("/a.b/c")).toBe("^\\/a\\.b\\/c\\/?(?:\\?.*)?$");
    expect(new RegExp(routeSource("/a.b")).test("/aXb")).toBe(false);
  });
});

describe("deploy/web/spa-routes.txt (generated from routes.config.ts)", () => {
  const txt = readFileSync(path.join(root, "deploy/web/spa-routes.txt"), "utf8");
  const lines = txt.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));

  it("lists exactly SPA_ROUTES, in order, with the computed exclusions", () => {
    const expected = SPA_ROUTES.map((r) => `=${r}${exclusionsFor(r, pages).map((e) => ` !${e}`).join("")}`);
    expect(lines).toEqual(expected);
  });

  it("nginx include generated by gen-routes.sh classifies paths like the SPA's isSpaPath", () => {
    const dir = mkdtempSync(path.join(tmpdir(), "spa-gen-"));
    try {
      execFileSync("bash", [path.join(root, "deploy/web/gen-routes.sh"), "--out", path.join(dir, "r.conf"), "--sw-out", path.join(dir, "sw.conf")], { stdio: "pipe" });
      const conf = readFileSync(path.join(dir, "r.conf"), "utf8");
      const regs = [...conf.matchAll(/^location ~ (\S+) \{/gm)].map((m) => new RegExp(m[1]));
      expect(regs.length).toBeGreaterThan(0);
      const nginx = (p: string) => regs.some((re) => re.test(p.split("?")[0]));
      const corpus = [
        "/", "/more", "/more/", "/more/x", "/settings", "/settings/", "/settings/about", "/settings/general", "/dashboard", "/dashboard/", "/dashboardx",
        "/transactions", "/transactions/new", "/transactions/search", "/transactions/12", "/transactions/12/edit", "/transactions/12/edit/", "/transactions/12/split",
        "/transactions/audit", "/transactions/audit/edit", "/transactions/transfer/ab/edit", "/transactions/new/edit",
        "/accounts", "/accounts/new", "/accounts/groups", "/accounts/12", "/accounts/12/", "/accounts/12/edit", "/accounts/grouped", "/categories", "/categories/5",
        "/filter/accounts", "/filter/categories", "/filter", "/filter/a/b", "/api/accounts", "/web/assets/x.js", "/budgets", "/portfolio/new/buy",
      ];
      for (const p of corpus) expect(nginx(p), `nginx vs SPA for ${p}`).toBe(isSpa(p));
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
